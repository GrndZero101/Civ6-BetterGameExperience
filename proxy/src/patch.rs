    /// Every game address written in the sources is in the table: none relies on a neighbour's shift.
    #[test]
    fn every_address_of_the_sources_is_in_the_table() {
        let dir = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("src");
        let mut missing = Vec::new();
        for entry in std::fs::read_dir(dir).unwrap() {
            let path = entry.unwrap().path();
            // This file holds the table itself.
            if path.extension().is_none_or(|e| e != "rs") || path.file_name().is_some_and(|n| n == "patch.rs") {
                continue;
            }
            let text = std::fs::read_to_string(&path).unwrap();
            for line in text.lines() {
                let code = line.split("//").next().unwrap();
                for (i, _) in code.match_indices("0x1_80") {
                    let digits: String = code[i + 2..].chars().take_while(|c| c.is_ascii_hexdigit() || *c == '_').filter(|c| *c != '_').collect();
                    let Ok(addr) = u64::from_str_radix(&digits, 16) else { continue };
                    if digits.len() == 9 && addr != IMAGE_BASE && MOVED.binary_search_by_key(&addr, |m| m.0).is_err() {
                        missing.push(format!("{}: {addr:#x}", path.file_name().unwrap().to_string_lossy()));
                    }
                }
            }
        }
        assert!(missing.is_empty(), "{missing:?}");
    }

